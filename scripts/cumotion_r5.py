def hand_joint_positions(actuated):
    """The ten hand joints from HomeHero's six actuated channels."""
    a = [float(v) for v in actuated]
    out = {}
    for k, d in enumerate(("index", "middle", "ring", "pinky")):
        out[f"psyonic_left_{d}_q1"] = a[k]
        out[f"psyonic_left_{d}_q2"] = a[k] * COUPLING
    out["psyonic_left_thumb_q2"] = a[4]
