def load(out: Path = OUT, joint_positions: dict | None = None):
    """The robot description; joint_positions override the XRDF's fixed-joint
    defaults (the hand as it will be during the plan: a preshape, not the
    rest - planned with the rest hand, the thumb grazed pieces the mesh
    screen caught)."""
    import yaml
    cumotion = _cumotion()
    sys.path.insert(0, str(ISAAC / "exts/isaacsim.robot_motion.cumotion/isaacsim/robot_motion/cumotion/impl"))
    from urdf_normalize import normalize_urdf_for_urdfdom
    urdf = normalize_urdf_for_urdfdom((out / "robot.urdf").read_text())
    xrdf = (out / "robot.xrdf").read_text()
    if joint_positions:
        x = yaml.safe_load(xrdf)
        for k, v in joint_positions.items():
            if k in x["default_joint_positions"]:
                x["default_joint_positions"][k] = round(float(v), 6)
        xrdf = yaml.safe_dump(x, sort_keys=False, default_flow_style=None)
    desc = cumotion.load_robot_from_memory(xrdf, urdf)
    return cumotion, desc


class Boxes:
    """Axis-aligned world boxes as cuMotion cuboids in the robot base frame."""

    def __init__(self, cumotion, base_pose):
        self.cm = cumotion
        self.world = cumotion.create_world()
        t = np.asarray(base_pose[:3], float)
        x, y, z, w = base_pose[3:]
        self.R = np.array([[1 - 2 * (y * y + z * z), 2 * (x * y - z * w), 2 * (x * z + y * w)],
                           [2 * (x * y + z * w), 1 - 2 * (x * x + z * z), 2 * (y * z - x * w)],
                           [2 * (x * z - y * w), 2 * (y * z + x * w), 1 - 2 * (x * x + y * y)]])
        self.t = t
        self.handles = []

    def add(self, lo, hi, inflate=None):
        inflate = float(os.environ.get("CUMOTION_INFLATE", "0.0")) if inflate is None else inflate
        lo, hi = np.asarray(lo, float) - inflate, np.asarray(hi, float) + inflate
        c_w = (lo + hi) / 2
        c_b = self.R.T @ (c_w - self.t)
        R_b = self.R.T                                       # the box's world axes, seen from the base
        ob = self.cm.create_obstacle(self.cm.Obstacle.Type.CUBOID)
        ob.set_attribute(self.cm.Obstacle.Attribute.SIDE_LENGTHS, self.cm.Obstacle.AttributeValue(hi - lo))
        pose = self.cm.Pose3(self.cm.Rotation3.from_matrix(R_b), c_b)
        self.handles.append(self.world.add_obstacle(ob, pose))

    def add_static_parts(self, desc, q=None, out: Path = OUT):
        """The robot's own static links (chassis, head) as boxes in the base
        frame, each collision part's box at its link's pose."""
        kin = desc.kinematics()
        q = desc.default_cspace_configuration() if q is None else np.asarray(q, float)
        static = json.loads((out / "static_parts.json").read_text())
        n = 0
        for link, parts in static.items():
            if link not in kin.frame_names():
                continue
            pose = kin.pose(q, link)
            for part in parts:
                lo, hi = np.asarray(part["min"], float), np.asarray(part["max"], float)
                ob = self.cm.create_obstacle(self.cm.Obstacle.Type.CUBOID)
                ob.set_attribute(self.cm.Obstacle.Attribute.SIDE_LENGTHS, self.cm.Obstacle.AttributeValue(hi - lo))
                self.handles.append(self.world.add_obstacle(ob, pose * self.cm.Pose3.from_translation((lo + hi) / 2)))
                n += 1
        return n

    def add_sdf_parts(self, desc, q=None, out: Path = OUT):
        """The big static parts (the chassis) as cuMotion SDF obstacles from
        chassis_sdf.py's grids: values positive outside, the obstacle's pose
        the grid's corner (measured with an analytic cube)."""
        kin = desc.kinematics()
        q = desc.default_cspace_configuration() if q is None else np.asarray(q, float)
        parts = json.loads((out / "sdf_parts.json").read_text()) if (out / "sdf_parts.json").exists() else []
        for part in parts:
            z = np.load(out / f"sdf_{part['link']}_{part['part']}.npz")
            vals, origin, voxel = z["values"].astype(np.float32), np.asarray(z["origin"], float), float(z["voxel"])
            nx, ny, nz = vals.shape
            ob = self.cm.create_obstacle(self.cm.Obstacle.Type.SDF)
            ob.set_attribute(self.cm.Obstacle.Attribute.GRID, self.cm.Obstacle.AttributeValue(
                self.cm.Obstacle.Grid(nx, ny, nz, voxel, self.cm.Obstacle.GridPrecision.FLOAT, self.cm.Obstacle.GridPrecision.FLOAT)))
            pose = kin.pose(q, part["link"]) * self.cm.Pose3.from_translation(origin)
            h = self.world.add_obstacle(ob, pose)
            self.world.set_sdf_grid_values_from_host(h, vals)
            errs = self.world.inspect_sdf(h, self.cm.World.SdfInspectionTolerances(1e-4, 1e-4)).num_errors()
            if errs:
                print(f"[sdf] {part['link']} part {part['part']}: {errs} inspection errors", file=sys.stderr)
            self.handles.append(h)
        return len(parts)

    def view(self):
        return self.world.add_world_view()


def main() -> int:
    cmd = sys.argv[1] if len(sys.argv) > 1 else "check"
    if cmd == "build":
        posture = {}
        if len(sys.argv) > 2:
            posture = json.loads(Path(sys.argv[2]).read_text()).get("joint_positions", {})
        out = build(posture)
        print(json.dumps(json.loads((out / "build.json").read_text())["spheres"]))
        return 0
    if cmd == "coverage":
        import yaml
        sp = yaml.safe_load((OUT / "robot.xrdf").read_text())["geometry"]["r5_spheres"]["spheres"]
        import trimesh
        print(f"{'link':34} {'verts':>6} {'spheres':>7} {'max gap mm':>10} {'mean mm':>8} {'max proud mm':>12}")
        for link, parts in sorted(_link_meshes().items()):
            if link not in sp:
                continue
            V, F = _mesh(parts)
            C = np.array([s["center"] for s in sp[link]])
            R = np.array([s["radius"] for s in sp[link]])
            gap = np.clip((np.linalg.norm(V[:, None, :] - C[None, :, :], axis=2) - R[None, :]).min(1), 0, None)
            tm = trimesh.Trimesh(V, F, process=False)
            _, dist, _ = trimesh.proximity.closest_point(tm, C)
            proud = R - np.where(tm.contains(C), dist, -dist)          # how far a sphere sticks out of its own mesh
            print(f"{link:34} {len(V):6} {len(C):7} {1000 * gap.max():10.1f} {1000 * gap.mean():8.1f} {1000 * proud.max():12.1f}")
        return 0
    cumotion, desc = load()
    kin = desc.kinematics()
    print("cspace", [desc.cspace_coord_name(i) for i in range(desc.num_cspace_coords())])
    print("base frame", kin.base_frame_name(), "tool", desc.tool_frame_names())
    insp = cumotion.create_robot_world_inspector(desc)
    q0 = desc.default_cspace_configuration()
    print("spheres", insp.num_world_collision_spheres(), "self", insp.num_self_collision_spheres())
    print("self-collision at default", insp.in_self_collision(q0), insp.frames_in_self_collision(q0)[:6])
    return 0


if __name__ == "__main__":
    sys.exit(main())
