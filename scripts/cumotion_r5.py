def _link_meshes():
    """Each link's collision meshes from HomeHero's cache, in the link frame."""
    man = json.loads(CACHE.with_suffix(".json").read_text())
    data = np.load(CACHE.with_suffix(".npz"))
    out = {}
    for i, s in enumerate(man["shapes"]):
        pts = np.asarray(data[f"p{i}"], float)
        faces = np.asarray(data[f"f{i}"], np.int32) if f"f{i}" in data.files and data[f"f{i}"].size else None
        out.setdefault(s["link"], []).append((pts, faces))
    return out


def _mesh(parts):
    """One vertex/triangle set per link; hull-less parts get a convex hull."""
    import trimesh
    V, F = [], []
    for pts, faces in parts:
        if faces is None or len(faces) == 0:
            hull = trimesh.convex.convex_hull(pts)
            pts, faces = np.asarray(hull.vertices), np.asarray(hull.faces, np.int32)
        F.append(np.asarray(faces, np.int32) + sum(len(v) for v in V))
        V.append(pts)
    return np.vstack(V), np.vstack(F)


RADIUS_OFFSET = float(os.environ.get("CUMOTION_RADIUS_OFFSET", "0.002"))  # grown onto every sphere (m)
MAX_OVERSHOOT = float(os.environ.get("CUMOTION_MAX_OVERSHOOT", "0.002"))  # how far a sphere may stick out of its mesh (m);
                                                                          # the generator's default is 0.05: link_1's spheres
                                                                          # stood 26 mm proud of the housing and "hit" the chassis


COVER_TOL = float(os.environ.get("CUMOTION_COVER_TOL", "0.003"))      # a vertex counts as covered within this of a sphere (m)


def _spheres(cumotion, link, parts, n):
    """Up to n spheres covering the link's surface: chosen greedily from
    cuMotion's medial-axis samples (each touches the surface from inside, so
    none protrudes) to cover the most mesh vertices within COVER_TOL of a
    sphere; RADIUS_OFFSET then grown onto each. (cuMotion's own selection,
    generate_spheres, stood up to 26 mm proud of the housing at its default
    5 cm overshoot, and covered little at 2 mm.)"""
    V, F = _mesh(parts)
    gen = cumotion.create_collision_sphere_generator([v for v in V], [f for f in F])
    if gen.num_triangles() == 0:
        raise RuntimeError(f"{link}: no valid triangles")
    S = gen.get_sampled_spheres()
    C = np.array([np.asarray(s.center, float) for s in S])
    R = np.array([float(s.radius) for s in S])
    if len(C) == 0:
        raise RuntimeError(f"{link}: no medial samples")
    rng = np.random.default_rng(0)
    P = V if len(V) <= 6000 else V[rng.choice(len(V), 6000, replace=False)]
    covers = np.linalg.norm(P[None, :, :] - C[:, None, :], axis=2) <= (R + RADIUS_OFFSET + COVER_TOL)[:, None]
    chosen, uncovered = [], np.ones(len(P), bool)
    while len(chosen) < n and uncovered.any():
        gain = (covers & uncovered[None, :]).sum(1)
        i = int(np.argmax(gain))
        if gain[i] == 0:
            break
        chosen.append(i)
        uncovered &= ~covers[i]
    return [(C[i], float(R[i]) + RADIUS_OFFSET) for i in chosen]


def _adjacency(urdf: Path):
    """Link pairs joined by a joint, fixed joints collapsed (as HomeHero's
    checker ignores them): these never count as self-collision."""
    root = ET.parse(urdf).getroot()
    links = [l.get("name") for l in root.findall("link")]
    parent = {l: l for l in links}

    def group(n):
        while parent[n] != n:
            n = parent[n]
        return n
    joints = root.findall("joint")
    for j in joints:
        if j.get("type") == "fixed":
            parent[group(j.find("child").get("link"))] = group(j.find("parent").get("link"))
    groups = {l: group(l) for l in links}
    pairs = set()
    for j in joints:
        a, b = groups[j.find("parent").get("link")], groups[j.find("child").get("link")]
        if a != b:
            pairs.add(frozenset((a, b)))
    return groups, pairs, root


def build(posture: dict | None = None) -> Path:
    """Write robot.urdf (velocity limits set) and robot.xrdf (spheres,
    cspace, fixed joints at the posture, tool frame, self-collision ignores)."""
    import yaml
    cumotion = _cumotion()
    robot = json.loads(ROBOT_JSON.read_text())
    urdf_src = Path(robot["physics"]["urdf"])
    OUT.mkdir(parents=True, exist_ok=True)
    groups, adjacent, root = _adjacency(urdf_src)
    # the URDF: arm velocity limits (0 in the source) from the commissioned action limits
    tree = ET.parse(urdf_src)
    for j in tree.getroot().findall("joint"):
        lim = j.find("limit")
        if lim is not None and j.get("name") in ARM:
            lim.set("velocity", str(VEL[ARM.index(j.get("name"))]))
            if float(lim.get("effort", "0") or 0) <= 0:
                lim.set("effort", "100")
        elif lim is not None:
            if float(lim.get("velocity", "0") or 0) <= 0:
                lim.set("velocity", "1.0")
            if float(lim.get("effort", "0") or 0) <= 0:
                lim.set("effort", "10")
    tree.write(OUT / "robot.urdf")
    # spheres
    meshes = _link_meshes()
    spheres = {}
    t0 = time.time()
    for link, parts in meshes.items():
        if not link.startswith(("amber_left_", "psyonic_left_")) or link in STATIC:
            continue                                        # the right arm and the wheels never meet the left arm here
        if "wheel" in link or "caster" in link:
            continue
        n = SPHERES.get(link, FINGER)
        try:
            spheres[link] = _spheres(cumotion, link, parts, n)
        except RuntimeError as e:
            print(f"[spheres] {link}: {e}", file=sys.stderr)
    print(f"[spheres] {sum(len(v) for v in spheres.values())} spheres on {len(spheres)} links in {time.time() - t0:.1f} s")
    # fixed joints at the posture
    posture = posture or {}
    defaults = {}
    for j in root.findall("joint"):
        n, t = j.get("name"), j.get("type")
        if t in ("fixed", "continuous") or n in ARM or j.find("mimic") is not None:
            continue                                        # a mimic joint follows its leader; cuMotion sets it;
                                                            # a continuous joint (wheels, casters) has no limits to hold it in
        defaults[n] = float(posture.get(n, 0.0))
    # self-collision ignores: adjacent groups, and everything within a group
    by_group = {}
    for l in spheres:
        by_group.setdefault(groups[l], []).append(l)
    ignore = {l: set() for l in spheres}
    for l in spheres:
        for m in spheres:
            if m == l:
                continue
            if groups[l] == groups[m] or frozenset((groups[l], groups[m])) in adjacent:
                ignore[l].add(m)
    # the fingers of one hand are set by the grip, not planned: ignore among themselves
    hand = [l for l in spheres if l.startswith("psyonic_left_")]
    for l in hand:
        ignore[l].update(m for m in hand if m != l)
    names = sorted(spheres)
    ign = {}
    for i, l in enumerate(names):
        later = [m for m in names[i + 1:] if m in ignore[l]]
        if later:
            ign[l] = later
    xrdf = {
        "format": "xrdf", "format_version": 2.0,
        "default_joint_positions": {k: round(v, 6) for k, v in defaults.items()},
        "cspace": {"joint_names": ARM, "acceleration_limits": [2.0] * 8, "jerk_limits": [500.0] * 8},
        "tool_frames": [PALM],
        "world_collision": {"geometry": "r5_world_spheres"},
        "self_collision": {"geometry": "r5_spheres", "ignore": ign},
        "geometry": {"r5_spheres": {"spheres": {
            l: [{"center": [round(float(c), 5) for c in cen], "radius": round(r, 5)} for cen, r in sp]
            for l, sp in spheres.items()}},
                     "r5_world_spheres": {"spheres": {
            l: [{"center": [round(float(c), 5) for c in cen], "radius": round(r, 5)} for cen, r in sp]
            for l, sp in spheres.items() if l not in MOUNT}}},
    }
    (OUT / "robot.xrdf").write_text(yaml.safe_dump(xrdf, sort_keys=False, default_flow_style=None))
    static = {}
    for link in STATIC:
        for pts, faces in meshes.get(link, []):
            lo, hi = pts.min(0), pts.max(0)
            if np.prod(hi - lo) > BIG_PART_M3:
                # the chassis shell: its box would swallow the arm's mount,
                # and 2.5 cm surface voxels put walls through the shoulder
                # housing (both measured); it is a signed-distance field
                # instead (chassis_sdf.py, Boxes.add_sdf_parts)
                continue
            else:
                static.setdefault(link, []).append({"min": lo.round(5).tolist(), "max": hi.round(5).tolist()})
    (OUT / "static_parts.json").write_text(json.dumps(static))
    print(f"[static] {sum(len(v) for v in static.values())} boxes on {len(static)} links")
    (OUT / "build.json").write_text(json.dumps({"urdf": str(urdf_src), "cache": str(CACHE), "radius_offset_m": RADIUS_OFFSET,
                                                 "spheres": {l: len(v) for l, v in spheres.items()},
                                                 "velocity_limits": dict(zip(ARM, VEL))}, indent=1))
    return OUT


